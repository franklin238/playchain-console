// Copies the PlayChainArcade ABI from the Foundry build into the web app.
// Run `forge build` in ../contracts first.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const artifact = JSON.parse(readFileSync(here("../../contracts/out/PlayChainArcade.sol/PlayChainArcade.json"), "utf8"));
const out = `// Generated by scripts/sync-abi.mjs from contracts/out. Do not edit by hand.\nexport const arcadeAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
writeFileSync(here("../src/config/arcadeAbi.ts"), out);
console.log(`Wrote ${artifact.abi.length} ABI entries.`);
